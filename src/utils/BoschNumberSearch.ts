function prepareCode(s: string): string {
    s = s.replace(/\s+/g, "");
    if (s.startsWith("0") || s.startsWith("1")) {
        s = s.slice(1);
    }
    return s;
}


function searchInPoolMap(poolMap: { yv: string, bosch: string }[], target: string[]) {
    const foundMap: { yv: string, search: string, pool: string, normalized: string }[] = [];

    for (const item of target) {

        for (const mapItem of poolMap) {
            const preparedboschCodes = mapItem.bosch.split(', ').map(code => prepareCode(code));
            if (preparedboschCodes.includes(prepareCode(item))) {
                foundMap.push({
                    yv: mapItem.yv,
                    search: item,
                    pool: mapItem.bosch,
                    normalized: prepareCode(item)
                });
            }
        }
    }

    return foundMap;

}



