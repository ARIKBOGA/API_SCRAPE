async function OE_Scraper_By_Walburg_Number(page: Page, walNo: string) {

    await page.goto(baseURL);

    const searchBox = page.getByRole('textbox', { name: 'Arama' });
    await searchBox.fill(walNo);
    await searchBox.press('Enter');

    await page.waitForLoadState('networkidle');
    await page.waitForLoadState('domcontentloaded');

    const products = page.locator("#ProductPageProductList .productItem");

    let result: { walNo: string; oe: string | null };

    if (await products.count() > 0) {
        const target = products.filter({
            has: page.locator(`.productStokKodu span:text-is("${walNo}")`)
        });

        // ürünün href’ini al
        const href = await target.locator("a.detailLink").first().getAttribute("href");

        if (href) {
            await page.goto(baseURL + href, { waitUntil: "domcontentloaded" });
            await page.waitForLoadState("networkidle");

            await page.waitForSelector("#spnBarkod");
            const oe = (await page.locator("#spnBarkod").textContent())?.trim();
            result = { walNo, oe: oe ?? null };
        } else {
            result = { walNo, oe: null };
        }
    } else {
        result = { walNo, oe: null };
    }


    // Thread-safe (atomic) dosya append
    //await fs.promises.appendFile(fileName, JSON.stringify(result) + "\n");
}


