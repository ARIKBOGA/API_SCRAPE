const filepath = path.resolve(__dirname, 'jsons/results.jsonl');

for (const kentparNo of kentparNumbers.slice(0, 10)) {
    test(`Find OE Numbers for Kentpar No: ${kentparNo}`, async ({ page }) => {
        await page.goto('https://www.kentpar.com.tr/tr-TR');

        await page.waitForLoadState('domcontentloaded');
        await expect(page.getByRole('searchbox', { name: 'Aramaya başlayın...' })).toBeVisible({ timeout: 15000 });
        await page.getByRole('searchbox', { name: 'Aramaya başlayın...' }).fill(kentparNo);
        await page.getByRole('button', { name: '' }).click();

        await page.waitForSelector('.p-product > .p-product__item', { timeout: 15000 });
        expect(page.locator('.p-product > .p-product__item')).not.toBeUndefined();
        await page.locator('.p-product > .p-product__item').filter({ hasText: kentparNo }).first().click();

        await page.waitForSelector('role=list', { timeout: 15000 });
        const oeNumbers = await page.locator('.p-product__detail-list-body > li:first-child').allInnerTexts();
        const oeNumbersUnique = Array.from(new Set(oeNumbers.map(oe => oe.trim()).filter(oe => oe !== '')));
        const result = { kentparNo, oeNumbers: oeNumbersUnique };

        await fs.promises.appendFile(filepath, JSON.stringify(result) + '\n', 'utf8');
        console.log(`Saved OE numbers for Kentpar No: ${kentparNo}`);
    });
}



